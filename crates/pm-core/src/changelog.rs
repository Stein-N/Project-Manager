//! Changelog of the current mod version: commits since the last version, a generated draft (with or without Claude)
//! and the files `CHANGELOG.md` (only the current version) and `CHANGELOG_FULL.md` (all older versions, newest
//! first).

use crate::commits;
use crate::git::Git;
use crate::util::read_or_empty;
use anyhow::Result;
use pm_types::{ChangelogAction, ChangelogPlan, ChangelogStart, Commit};
use regex::Regex;
use std::fs;
use std::path::Path;
use std::sync::LazyLock;

pub const FILE: &str = "CHANGELOG.md";
pub const FULL_FILE: &str = "CHANGELOG_FULL.md";
pub const FULL_HEADER: &str = "# Changelog";
/// Second line of every entry written by Claude.
pub const AI_NOTE: &str = "> This changelog was generated by AI";

/// A heading of any level that starts with a version: `## 1.4.0 – …`, `#### v2.1.6`, `## [1.4.0]`.
static HEADING_VERSION: LazyLock<fancy_regex::Regex> =
    LazyLock::new(|| fancy_regex::Regex::new(r"(?m)^#{1,6}\s+\[?[vV]?(\d[\w.+-]*?)]?(?=\s|$|]|\))").unwrap());
static VERSION_PROPERTY: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?m)^\s*(mod_version|modVersion|version)\s*[=:]\s*(\S+)\s*$").unwrap());
static ANY_HEADING: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^(#{1,6})\s+(.*)$").unwrap());

