        assert_eq!(detect_version("# Changelog\n\n## [1.4.0] - 2026-10-17").as_deref(), Some("1.4.0"));
        assert_eq!(detect_version("## v1.4.0-beta.2\n### Fixed").as_deref(), Some("1.4.0-beta.2"));
        assert_eq!(detect_version("## 2.0.0+1.21.1").as_deref(), Some("2.0.0+1.21.1"));
