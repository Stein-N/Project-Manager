/// `### v2.1.7` – the mod version only: all Minecraft versions of a mod carry the same mod version, the Minecraft
/// part in `version` just keeps the file names apart on CurseForge and Modrinth.
pub fn heading(version: &str) -> String {
    format!("### v{version}")
}

/// Draft without Claude: one bullet per commit subject, oldest first, below the heading.
pub fn fallback(heading: &str, commits: &[Commit]) -> String {
    let mut sb = format!("{heading}\n\n");
    let mut entries = 0;
    for c in commits.iter().rev() {
        let subject = c.message.subject.trim();
        if subject.is_empty() {
            continue;
        }
        sb.push_str(&format!("- {}{subject}\n", if c.message.breaking { "**breaking:** " } else { "" }));
        entries += 1;
    }
    if entries == 0 {
        sb.push_str("- no notable changes\n");
    }
    sb
}

/// Puts [`AI_NOTE`] below the heading if Claude left it out.
pub fn with_ai_note(entry: &str) -> String {
    if entry.contains(AI_NOTE) {
        return entry.to_string();
    }
    let text = entry.replace("\r\n", "\n");
    match text.find('\n') {
        None => format!("{text}\n{AI_NOTE}\n"),
        Some(nl) => {
            let rest = &text[nl + 1..];
            format!("{}{AI_NOTE}\n{}{rest}", &text[..=nl], if rest.starts_with('\n') { "" } else { "\n" })
        }
    }
}

/// Prompt for Claude (which gets no tools: everything it needs is in here).
///
/// * `diff` – net code changes of the range (see [`diff`])
/// * `style_sample` – an earlier entry written by Claude (see [`ai_style_sample`])
/// * `rules` – changelog section of the repo's CLAUDE.md
#[allow(clippy::too_many_arguments)]
pub fn prompt(
    mod_name: &str,
    loader: Option<&str>,
    mc_version: Option<&str>,
    heading: &str,
    commits: &[Commit],
    diff: Option<&str>,
    style_sample: Option<&str>,
    rules: Option<&str>,
) -> String {
    let release = heading.trim_start_matches('#').trim_start();
    let mut sb = format!("Write the changelog entry for the release {release} of the Minecraft mod \"{mod_name}\"");
    let about: Vec<String> = [loader.map(str::to_string), mc_version.map(|m| format!("Minecraft {m}"))]
        .into_iter()
        .flatten()
        .filter(|s| !s.trim().is_empty() && s != "Minecraft ")
        .collect();
    if !about.is_empty() {
        sb.push_str(&format!(" ({})", about.join(", ")));
    }
    sb.push_str(".\n\n");
    sb.push_str(&format!(
        r#"Format (answer with the Markdown entry only – no explanations, no code fences):
- Line 1 exactly: {heading}
- Line 2 exactly: {AI_NOTE}
- Then one blank line and a list of "- " bullets. Put details of a change into sub-bullets indented by
  two spaces ("  - "). No other headings, no sections, no blank lines inside the list.
- Breaking changes first, each starting with "**breaking:** " (lower case), then the other changes.
- Start the other bullets with a lower-case verb in -ing form: "adding …", "fixing …", "removing …",
  "changing …".

Content:
- Describe what changed for the users of the mod: for a library its public API (classes, methods,
  data components, registries) and how to migrate, for a content mod the gameplay.
- Write class, method, field, component and resource names in backticks, exactly as in the code.
- Say what replaces something that was removed or renamed ("use … instead").
- One top-level bullet per change; important details (behavior, loader differences, migration) as
  sub-bullets. Merge follow-up fixes of the same change into it.
- Keep it compact like a release note: usually 1-3 sub-bullets per change, at most 5. Leave out what
  users do not need (internal classes, constants, limits, exception types, how a loader implements
  something) unless it changes how the mod is used.
- Leave out internal changes (refactoring, cleanup, imports, tests, build scripts, CI, version bumps)
  unless they change behavior for users.
- The diff shows what actually changed, the commit messages show the intent. Do not invent anything
  that is in neither.
- English, concise.

Example of the format (made-up content):
<<<
{FORMAT_EXAMPLE}>>>
"#
    ));
    if let Some(sample) = style_sample.filter(|s| !s.trim().is_empty()) {
        sb.push_str(&format!(
            "\nAn earlier entry of this mod (match its style and level of detail):\n<<<\n{}\n>>>\n",
            sample.trim()
        ));
    }
    if let Some(rules) = rules.filter(|r| !r.trim().is_empty()) {
        sb.push_str(&format!("\nProject-specific changelog rules (they take precedence):\n{}\n", rules.trim()));
    }
    sb.push_str("\nCommits of this release (oldest first):\n");
    for c in commits.iter().rev() {
        let m = &c.message;
        sb.push_str(&format!("\n- {} ", c.short_sha));
        if let Some(kind) = &m.kind {
            sb.push_str(&format!(
                "[{kind}{}{}] ",
                m.scope.as_ref().map(|s| format!("({s})")).unwrap_or_default(),
                if m.breaking { ", breaking" } else { "" }
            ));
        }
        sb.push_str(&m.subject);
        if m.is_backport() {
            sb.push_str(" (backport)");
        }
        let body = commits::body_without_trailers(m);
        if !body.is_empty() {
            sb.push_str(&format!("\n  {}", body.replace('\n', "\n  ")));
        }
    }
    sb.push('\n');
    if let Some(diff) = diff.filter(|d| !d.trim().is_empty()) {
        sb.push_str(&format!(
            "\nCode changes of this release (git diff, generated files, tests and binaries left out):\n<diff>\n{}\n</diff>\n",
            diff.trim()
        ));
    }
    sb
}

/// Paths left out of the diff: generated data, tests, CI, Gradle wrapper, binary assets and the changelogs.
const DIFF_EXCLUDES: [&str; 12] = [
    ":(exclude,glob)**/src/generated/**",
    ":(exclude,glob)**/src/test/**",
    ":(exclude,glob)**/gametest/**",
    ":(exclude,glob)**/test_instance/**",
    ":(exclude,glob).github/**",
    ":(exclude,glob)**/gradle/wrapper/**",
    ":(exclude,glob)**/*.png",
    ":(exclude,glob)**/*.jar",
    ":(exclude,glob)**/*.ogg",
    ":(exclude,glob)**/*.nbt",
    ":(exclude)CHANGELOG.md",
    ":(exclude)CHANGELOG_FULL.md",
];
const EMPTY_TREE: &str = "4b825dc642cb6eb9a060e54bf8d69288fbee4904";

/// Net code changes from `start` (None = whole history) to HEAD: file statistics and the patch, limited to about
/// `max_chars`. Files that do not fit any more are only listed.
pub fn diff(git: &Git, repo: &Path, start: Option<&str>, max_chars: usize) -> Result<String> {
    let from = start.unwrap_or(EMPTY_TREE);
    let mut stat = vec!["diff", "--stat=160", "--no-color", from, "HEAD", "--", "."];
    stat.extend(DIFF_EXCLUDES);
    let mut patch = vec!["diff", "--no-color", "--unified=3", from, "HEAD", "--", "."];
    patch.extend(DIFF_EXCLUDES);
    Ok(limit_diff(&git.output(repo, &stat)?, &git.output(repo, &patch)?, max_chars))
}

pub fn limit_diff(summary: &str, patch: &str, max_chars: usize) -> String {
    let mut sb = format!("{}\n\n", summary.trim());
    let mut omitted = Vec::new();
    for file in split_keep(patch, "diff --git ") {
        if file.trim().is_empty() {
            continue;
        }
        if sb.len() + file.len() <= max_chars {
            sb.push_str(file);
            if !file.ends_with('\n') {
                sb.push('\n');
            }
        } else {
            let first = file.lines().next().unwrap_or("");
            let name = first.strip_prefix("diff --git a/").and_then(|r| r.split(" b/").next()).unwrap_or(first);
            omitted.push(name.to_string());
        }
    }
    if !omitted.is_empty() {
        sb.push_str(&format!(
            "\n(diff of {} more file(s) left out because of its size: {})\n",
            omitted.len(),
            omitted.join(", ")
        ));
    }
    sb
}

/// Splits `text` before every line that starts with `marker`.
fn split_keep<'a>(text: &'a str, marker: &str) -> Vec<&'a str> {
    let mut starts: Vec<usize> =
        text.match_indices(marker).map(|(i, _)| i).filter(|&i| i == 0 || text.as_bytes()[i - 1] == b'\n').collect();
    if starts.first() != Some(&0) {
        starts.insert(0, 0);
    }
    starts.iter().enumerate().map(|(n, &s)| &text[s..starts.get(n + 1).copied().unwrap_or(text.len())]).collect()
}

/// Cleans Claude's answer; None if it does not start with a heading for `version`.
pub fn clean_answer(answer: &str, version: &str) -> Option<String> {
    let mut text = answer.replace("\r\n", "\n").trim().to_string();
    for fence in ["```markdown\n", "```md\n", "```\n"] {
        if let Some(rest) = text.strip_prefix(fence) {
            text = rest.to_string();
            break;
        }
    }
    if let Some(rest) = text.strip_suffix("\n```") {
        text = rest.to_string();
    }
    let text = text.trim();
    let start = first_version_heading(text)?;
    let text = &text[start..];
    detect_version(text).filter(|v| same_version(v, version)).map(|_| format!("{text}\n"))
}

/// The section about changelogs from a CLAUDE.md (a heading containing "changelog").
pub fn rules_from_claude_md(claude_md: &str) -> Option<String> {
    let mut sb: Option<String> = None;
    let mut level = 0;
    for line in claude_md.replace("\r\n", "\n").split('\n') {
        if let Some(h) = ANY_HEADING.captures(line) {
            let l = h[1].len();
            if sb.is_some() && l <= level {
                break;
            }
            if sb.is_none() && h[2].to_lowercase().contains("changelog") {
                sb = Some(String::new());
                level = l;
                continue;
            }
        }
        if let Some(s) = sb.as_mut() {
            s.push_str(line);
            s.push('\n');
        }
    }
    sb.map(|s| s.trim().to_string()).filter(|s| !s.is_empty())
}

