/// Version of the first heading that carries one: `## 1.4.0 – …`, `## [1.4.0]`, `#### v1.4.0`.
pub fn detect_version(markdown: &str) -> Option<String> {
    let text = markdown.replace("\r\n", "\n");
    HEADING_VERSION.captures(&text).ok().flatten().and_then(|c| c.get(1).map(|m| m.as_str().to_string()))
}

pub fn plan(dir: &Path, version: &str) -> ChangelogPlan {
    let current = read_or_empty(&dir.join(FILE));
    if current.trim().is_empty() {
        return ChangelogPlan { action: ChangelogAction::Create, old_version: None };
    }
    let Some(old) = detect_version(&current) else {
        return ChangelogPlan { action: ChangelogAction::UnknownContent, old_version: None };
    };
    let action = if same_version(&old, version) {
        ChangelogAction::ReplaceSameVersion
    } else if contains_version(&read_or_empty(&dir.join(FULL_FILE)), &old) {
        ChangelogAction::OldVersionAlreadyInFull
    } else {
        ChangelogAction::MoveOldVersion
    };
    ChangelogPlan { action, old_version: Some(old) }
}

/// Writes `content` to CHANGELOG.md; an older version found there first moves to the top of CHANGELOG_FULL.md.
/// `move_unknown`: for [`ChangelogAction::UnknownContent`] move the old content to CHANGELOG_FULL.md as well.
pub fn save(dir: &Path, version: &str, content: &str, move_unknown: bool) -> Result<ChangelogPlan> {
    let plan = plan(dir, version);
    if plan.action == ChangelogAction::MoveOldVersion
        || (plan.action == ChangelogAction::UnknownContent && move_unknown)
    {
        let full = dir.join(FULL_FILE);
        fs::write(&full, insert_into_full(&read_or_empty(&full), &read_or_empty(&dir.join(FILE))))?;
    }
    fs::write(dir.join(FILE), format!("{}\n", content.replace("\r\n", "\n").trim()))?;
    Ok(plan)
}

/// Puts `section` above the first version of `full` (after its header).
pub fn insert_into_full(full: &str, section: &str) -> String {
    let entry = format!("{}\n", section.replace("\r\n", "\n").trim());
    let text = full.replace("\r\n", "\n");
    if text.trim().is_empty() {
        return format!("{FULL_HEADER}\n\n{entry}");
    }
    match first_version_heading(&text) {
        None => format!("{}\n\n{entry}", text.trim_end()),
        Some(first) => format!("{}{entry}\n{}", &text[..first], &text[first..]),
    }
}

pub fn contains_version(full: &str, version: &str) -> bool {
    let text = full.replace("\r\n", "\n");
    HEADING_VERSION.captures_iter(&text).flatten().any(|c| c.get(1).is_some_and(|m| same_version(m.as_str(), version)))
}

/// The newest entry written by Claude (one with [`AI_NOTE`]) from CHANGELOG.md, otherwise from CHANGELOG_FULL.md,
/// as a style sample; at most `max_lines` lines. Hand-written entries are not used: they are much shorter than what
/// Claude is asked for.
pub fn ai_style_sample(dir: &Path, max_lines: usize) -> Option<String> {
    for name in [FILE, FULL_FILE] {
        let text = read_or_empty(&dir.join(name)).replace("\r\n", "\n");
        let starts: Vec<usize> = HEADING_VERSION.find_iter(&text).flatten().map(|m| m.start()).collect();
        for (i, &s) in starts.iter().enumerate() {
            let entry = &text[s..starts.get(i + 1).copied().unwrap_or(text.len())];
            if entry.contains(AI_NOTE) {
                return Some(entry.trim().split('\n').take(max_lines).collect::<Vec<_>>().join("\n"));
            }
        }
    }
    None
}

/// Offset of the first heading with a version.
fn first_version_heading(text: &str) -> Option<usize> {
    HEADING_VERSION.find(text).ok().flatten().map(|m| m.start())
}

fn show(git: &Git, repo: &Path, sha: &str, path: &str) -> Option<String> {
    let out = git.run(Some(repo), &["show", &format!("{sha}:./{path}")]);
    out.ok().then_some(out.text)
}

fn abbrev(sha: &str) -> &str {
    &sha[..sha.len().min(7)]
}

