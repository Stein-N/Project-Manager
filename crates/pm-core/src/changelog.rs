/// Commits in `start..HEAD` (all commits for no start), newest first.
pub fn commits(git: &Git, repo: &Path, start: Option<&str>) -> Result<Vec<Commit>> {
    let range = start.map(|s| format!("{s}..HEAD")).unwrap_or_else(|| "HEAD".into());
    commits::log(git, repo, &[&range])
}

/// Candidates for the start of the range, the preferred one first: the last change of `CHANGELOG.md` if it holds
/// another version (= release of the previous version), then the commit that set `mod_version` to the current
/// value – or, if nothing was committed after that bump, the commit that set the previous value.
///
/// `mod_version` is the raw value from gradle.properties (`1.21.1-2.1.6`), `display_version` the version as
/// written in the changelog (see [`display_version`]).
pub fn starts(git: &Git, repo: &Path, mod_version: &str, display_version: &str) -> Vec<ChangelogStart> {
    let mut starts = Vec::new();
    if let Some(c) = git.value(repo, &["log", "-1", "--format=%H", "--", FILE])
        && let Some(version) = show(git, repo, &c, FILE).and_then(|t| detect_version(&t))
        && !same_version(&version, display_version)
    {
        starts.push(ChangelogStart { label: format!("CHANGELOG.md for {version} ({})", abbrev(&c)), sha: Some(c) });
    }

    // Commits that set a new value of the version property, newest first. "-G version" also finds changes of other
    // lines (minecraft_version, …); of several commits with the same value the oldest one set it.
    let mut bumps: Vec<(String, String)> = Vec::new();
    if let Some(log) = git.value(repo, &["log", "--format=%H", "-G", "version", "--", "gradle.properties"]) {
        for sha in log.lines().map(str::trim) {
            let Some(value) = show(git, repo, sha, "gradle.properties").and_then(|t| version_property(&t)) else {
                continue;
            };
            match bumps.last_mut() {
                Some(last) if last.1 == value => last.0 = sha.to_string(),
                _ => bumps.push((sha.to_string(), value)),
            }
        }
    }
    if let Some(i) = bumps.iter().position(|(_, v)| v == mod_version) {
        let (sha, value) = &bumps[i];
        // The bump commit itself belongs to the release: it often carries the first change of the new version.
        // Its parent is the start; for the root commit the whole history.
        let parent = git.value(repo, &["rev-parse", "--verify", "--quiet", &format!("{sha}^")]);
        let with_bump =
            ChangelogStart { sha: parent, label: format!("mod_version set to {value} ({}, included)", abbrev(sha)) };
        let previous = bumps.get(i + 1).map(|(s, v)| ChangelogStart {
            sha: Some(s.clone()),
            label: format!("mod_version set to {v} ({})", abbrev(s)),
        });
        let nothing_after = git.value(repo, &["rev-list", "--count", &format!("{sha}..HEAD")]).is_none_or(|n| n == "0");
        // bump as the very last commit = bumped at release time: then the previous bump starts the range
        match previous {
            Some(prev) if nothing_after => starts.extend([prev, with_bump]),
            Some(prev) => starts.extend([with_bump, prev]),
            None => starts.push(with_bump),
        }
    }
    starts.push(ChangelogStart { sha: None, label: "Whole history".into() });
    let mut seen = std::collections::HashSet::new();
    starts.retain(|s| seen.insert(s.sha.clone()));
    starts
}

pub fn version_property(gradle_properties: &str) -> Option<String> {
    let found: Vec<(String, String)> =
        VERSION_PROPERTY.captures_iter(gradle_properties).map(|m| (m[1].to_string(), m[2].to_string())).collect();
    ["mod_version", "modVersion", "version"]
        .iter()
        .find_map(|k| found.iter().find(|(key, _)| key == k).map(|(_, v)| v.clone()))
}

/// The mod version as written in the changelog: without a Minecraft prefix or suffix (`1.21.1-2.1.6` → `2.1.6`,
/// `2.1.6+1.21.1` → `2.1.6`).
pub fn display_version(mod_version: &str, mc_version: &str) -> String {
    let v = mod_version.trim();
    let mc = mc_version.trim();
    if !mc.is_empty() {
        for prefix in [format!("{mc}-"), format!("{mc}+"), format!("mc{mc}-")] {
            if let Some(rest) = v.strip_prefix(&prefix).filter(|r| !r.is_empty()) {
                return rest.to_string();
            }
        }
        for suffix in [format!("-{mc}"), format!("+{mc}"), format!("+mc{mc}"), format!("-mc{mc}")] {
            if let Some(rest) = v.strip_suffix(&suffix).filter(|r| !r.is_empty()) {
                return rest.to_string();
            }
        }
    }
    v.to_string()
}

/// Versions are equal ignoring a leading "v" (`v2.1.6` = `2.1.6`).
pub fn same_version(a: &str, b: &str) -> bool {
    strip_v(a).eq_ignore_ascii_case(strip_v(b))
}

fn strip_v(v: &str) -> &str {
    v.strip_prefix(['v', 'V']).unwrap_or(v)
}

