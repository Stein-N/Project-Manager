    #[test]
    fn start_after_bump_of_current_version() {
        let tmp = tempfile::tempdir().unwrap();
        let repo = init(tmp.path());
        write(&repo, "gradle.properties", "mod_version=1.0.0\n");
        commit(&repo, "init", &[]);
        commit(&repo, "fix: old fix", &["a.txt"]);
        write(&repo, "gradle.properties", "mod_version=1.1.0\n");
        commit(&repo, "chore: bump to 1.1.0", &[]);
        let bump = head(&repo);
        commit(&repo, "feat: new thing", &["b.txt"]);
        commit(&repo, "fix: other", &["c.txt"]);
        let s = starts(&git(), &repo, "1.1.0", "1.1.0");
        assert_eq!(s[0].sha, Some(sh(&repo, &["rev-parse", &format!("{bump}^")])));
        let list = commits(&git(), &repo, s[0].sha.as_deref()).unwrap();
        assert_eq!(
            list.iter().map(|c| c.message.subject.as_str()).collect::<Vec<_>>(),
            ["other", "new thing", "bump to 1.1.0"]
        );
        assert_eq!(s.last().unwrap().sha, None);
    }

