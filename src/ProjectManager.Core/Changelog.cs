    /// <summary>Version of the first heading that carries one: <c>## 1.4.0 – …</c>, <c>## [1.4.0]</c>, <c>#### v1.4.0</c>.</summary>
    public static string? DetectVersion(string markdown)
    {
        var m = HeadingVersion().Match(markdown.Replace("\r\n", "\n"));
        return m.Success ? m.Groups[1].Value : null;
    }

    public static ChangelogPlan Plan(string dir, string version)
    {
        var current = Util.ReadOrEmpty(Path.Combine(dir, File));
        if (current.Trim().Length == 0) return new ChangelogPlan(ChangelogAction.Create, null);
        if (DetectVersion(current) is not { } old) return new ChangelogPlan(ChangelogAction.UnknownContent, null);
        var action = SameVersion(old, version) ? ChangelogAction.ReplaceSameVersion
            : ContainsVersion(Util.ReadOrEmpty(Path.Combine(dir, FullFile)), old) ? ChangelogAction.OldVersionAlreadyInFull
            : ChangelogAction.MoveOldVersion;
        return new ChangelogPlan(action, old);
    }

    /// <summary>
    /// Writes <paramref name="content"/> to CHANGELOG.md; an older version found there first moves to the top of
    /// CHANGELOG_FULL.md. <paramref name="moveUnknown"/>: for <see cref="ChangelogAction.UnknownContent"/> move the old
    /// content to CHANGELOG_FULL.md as well.
    /// </summary>
    public static ChangelogPlan Save(string dir, string version, string content, bool moveUnknown)
    {
        var plan = Plan(dir, version);
        if (plan.Action == ChangelogAction.MoveOldVersion || (plan.Action == ChangelogAction.UnknownContent && moveUnknown))
        {
            var full = Path.Combine(dir, FullFile);
            Util.WriteText(full, InsertIntoFull(Util.ReadOrEmpty(full), Util.ReadOrEmpty(Path.Combine(dir, File))));
        }
        Util.WriteText(Path.Combine(dir, File), $"{content.Replace("\r\n", "\n").Trim()}\n");
        return plan;
    }

    /// <summary>Puts <paramref name="section"/> above the first version of <paramref name="full"/> (after its header).</summary>
    public static string InsertIntoFull(string full, string section)
    {
        var entry = $"{section.Replace("\r\n", "\n").Trim()}\n";
        var text = full.Replace("\r\n", "\n");
        if (text.Trim().Length == 0) return $"{FullHeader}\n\n{entry}";
        return FirstVersionHeading(text) is { } first ? $"{text[..first]}{entry}\n{text[first..]}" : $"{text.TrimEnd()}\n\n{entry}";
    }

    public static bool ContainsVersion(string full, string version) =>
        HeadingVersion().Matches(full.Replace("\r\n", "\n")).Any(m => SameVersion(m.Groups[1].Value, version));

    /// <summary>
    /// The newest entry written by Claude (one with <see cref="AiNote"/>) from CHANGELOG.md, otherwise from
    /// CHANGELOG_FULL.md, as a style sample; at most <paramref name="maxLines"/> lines. Hand-written entries are not
    /// used: they are much shorter than what Claude is asked for.
    /// </summary>
    public static string? AiStyleSample(string dir, int maxLines)
    {
        foreach (var name in new[] { File, FullFile })
        {
            var text = Util.ReadOrEmpty(Path.Combine(dir, name)).Replace("\r\n", "\n");
            var starts = HeadingVersion().Matches(text).Select(m => m.Index).ToList();
            for (var i = 0; i < starts.Count; i++)
            {
                var entry = text[starts[i]..(i + 1 < starts.Count ? starts[i + 1] : text.Length)];
                if (entry.Contains(AiNote) || entry.Contains(OldAiNote)) return string.Join("\n", entry.Trim().Split('\n').Take(maxLines));
            }
        }
        return null;
    }

    /// <summary>Offset of the first heading with a version.</summary>
    private static int? FirstVersionHeading(string text) => HeadingVersion().Match(text) is { Success: true } m ? m.Index : null;

    private static string? Show(Git git, string repo, string sha, string path)
    {
        var o = git.Run(repo, "show", $"{sha}:./{path}");
        return o.Ok ? o.Text : null;
    }

    private static string Abbrev(string sha) => sha[..Math.Min(7, sha.Length)];
}
