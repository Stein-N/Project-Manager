// Changelog of the current mod version: commits since the last version, a generated draft (with or without Claude) and
// the files CHANGELOG.md (only the current version) and CHANGELOG_FULL.md (all older versions, newest first).

using System.Text;
using System.Text.RegularExpressions;

namespace ProjectManager.Core;

public static partial class Changelog
{
    public const string File = "CHANGELOG.md";
    public const string FullFile = "CHANGELOG_FULL.md";
    public const string FullHeader = "# Changelog";

    /// <summary>Second line of every entry written by Claude.</summary>
    public const string AiNote = "> Changelog generated automatically";

    /// <summary>The note of older versions; entries with it still count as written by Claude.</summary>
    private const string OldAiNote = "> This changelog was generated by AI";

    /// <summary>A heading of any level that starts with a version: <c>## 1.4.0 – …</c>, <c>#### v2.1.6</c>, <c>## [1.4.0]</c>.</summary>
    [GeneratedRegex(@"^#{1,6}\s+\[?[vV]?(\d[\w.+-]*?)]?(?=\s|$|]|\))", RegexOptions.Multiline)]
    private static partial Regex HeadingVersion();

    [GeneratedRegex(@"^\s*(mod_version|modVersion|version)\s*[=:]\s*(\S+)\s*$", RegexOptions.Multiline)]
    private static partial Regex VersionProperty();

    [GeneratedRegex(@"^(#{1,6})\s+(.*)$")]
    private static partial Regex AnyHeading();

