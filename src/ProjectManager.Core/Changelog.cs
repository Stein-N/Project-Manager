    /// <summary>Shows Claude the expected format when the project has no entry written by Claude yet.</summary>
    public const string FormatExample = """
        ### v2.0.0
        > Changelog generated automatically

        - **breaking:** `FooRegistry.register(...)` takes a `ResourceKey<Foo>` instead of a `String`
          - `FooRegistry.get(...)` was removed, use `FooRegistry.lookup(...)` instead
        - **breaking:** `OldHelper` was removed, use `Helpers.create(...)` instead
        - adding the data component `examplemod:color` (`ModComponents.COLOR` / `ItemColor`)
          - saved and synced like vanilla components, so it also works with `/give` and datapacks
          - shown in the tooltip on all loaders
        - adding a config option to disable the particle effects
        - fixing a crash when a block entity was removed while its menu was open

        """;

    /// <summary>
    /// <c>### v2.1.7</c> – the mod version only: all Minecraft versions of a mod carry the same mod version, the
    /// Minecraft part in <c>version</c> just keeps the file names apart on CurseForge and Modrinth.
    /// </summary>
    public static string Heading(string version) => $"### v{version}";

    /// <summary>Draft without Claude: one bullet per commit subject, oldest first, below the heading.</summary>
    public static string Fallback(string heading, IReadOnlyList<Commit> commits)
    {
        var sb = new StringBuilder($"{heading}\n\n");
        var entries = 0;
        foreach (var c in commits.Reverse())
        {
            var subject = c.Message.Subject.Trim();
            if (subject.Length == 0) continue;
            sb.Append($"- {(c.Message.Breaking ? "**breaking:** " : "")}{subject}\n");
            entries++;
        }
        if (entries == 0) sb.Append("- no notable changes\n");
        return sb.ToString();
    }

    /// <summary>Puts <see cref="AiNote"/> below the heading if Claude left it out.</summary>
    public static string WithAiNote(string entry)
    {
        // Claude may copy the old note from a style sample
        entry = entry.Replace(OldAiNote, AiNote);
        if (entry.Contains(AiNote)) return entry;
        var text = entry.Replace("\r\n", "\n");
        var nl = text.IndexOf('\n');
        if (nl < 0) return $"{text}\n{AiNote}\n";
        var rest = text[(nl + 1)..];
        return $"{text[..(nl + 1)]}{AiNote}\n{(rest.StartsWith('\n') ? "" : "\n")}{rest}";
    }

    /// <summary>Prompt for Claude (which gets no tools: everything it needs is in here).</summary>
    /// <param name="diff">net code changes of the range (see <see cref="Diff"/>)</param>
    /// <param name="styleSample">an earlier entry written by Claude (see <see cref="AiStyleSample"/>)</param>
    /// <param name="rules">changelog section of the repo's CLAUDE.md</param>
    public static string Prompt(string modName, string? loader, string? mcVersion, string heading, IReadOnlyList<Commit> commits,
        string? diff, string? styleSample, string? rules)
    {
        var release = heading.TrimStart('#').TrimStart();
        var sb = new StringBuilder($"Write the changelog entry for the release {release} of the Minecraft mod \"{modName}\"");
        var about = new[] { loader, mcVersion is null ? null : $"Minecraft {mcVersion}" }
            .OfType<string>().Where(s => s.Trim().Length > 0 && s != "Minecraft ").ToList();
        if (about.Count > 0) sb.Append($" ({string.Join(", ", about)})");
        sb.Append(".\n\n");
        sb.Append($"""
            Format (answer with the Markdown entry only – no explanations, no code fences):
            - Line 1 exactly: {heading}
            - Line 2 exactly: {AiNote}
            - Then one blank line and a list of "- " bullets. Put details of a change into sub-bullets indented by
              two spaces ("  - "). No other headings, no sections, no blank lines inside the list.
            - Breaking changes first, each starting with "**breaking:** " (lower case), then the other changes.
            - Start the other bullets with a lower-case verb in -ing form: "adding …", "fixing …", "removing …",
              "changing …".

            Content:
            - Describe what changed for the users of the mod: for a library its public API (classes, methods,
              data components, registries) and how to migrate, for a content mod the gameplay.
            - Write class, method, field, component and resource names in backticks, exactly as in the code.
            - Say what replaces something that was removed or renamed ("use … instead").
            - One top-level bullet per change; important details (behavior, loader differences, migration) as
              sub-bullets. Merge follow-up fixes of the same change into it.
            - Keep it compact like a release note: usually 1-3 sub-bullets per change, at most 5. Leave out what
              users do not need (internal classes, constants, limits, exception types, how a loader implements
              something) unless it changes how the mod is used.
            - Leave out internal changes (refactoring, cleanup, imports, tests, build scripts, CI, version bumps)
              unless they change behavior for users.
            - The diff shows what actually changed, the commit messages show the intent. Do not invent anything
              that is in neither.
            - English, concise.

            Example of the format (made-up content):
            <<<
            {FormatExample}>>>

            """);
        if (styleSample is not null && styleSample.Trim().Length > 0)
            sb.Append($"\nAn earlier entry of this mod (match its style and level of detail):\n<<<\n{styleSample.Trim()}\n>>>\n");
        if (rules is not null && rules.Trim().Length > 0)
            sb.Append($"\nProject-specific changelog rules (they take precedence):\n{rules.Trim()}\n");
        sb.Append("\nCommits of this release (oldest first):\n");
        foreach (var c in commits.Reverse())
        {
            var m = c.Message;
            sb.Append($"\n- {c.ShortSha} ");
            if (m.Kind is { } kind)
                sb.Append($"[{kind}{(m.Scope is null ? "" : $"({m.Scope})")}{(m.Breaking ? ", breaking" : "")}] ");
            sb.Append(m.Subject);
            if (m.IsBackport) sb.Append(" (backport)");
            var body = Core.Commits.BodyWithoutTrailers(m);
            if (body.Length > 0) sb.Append($"\n  {body.Replace("\n", "\n  ")}");
        }
        sb.Append('\n');
        if (diff is not null && diff.Trim().Length > 0)
            sb.Append(
                $"\nCode changes of this release (git diff, generated files, tests and binaries left out):\n<diff>\n{diff.Trim()}\n</diff>\n");
        return sb.ToString();
    }

