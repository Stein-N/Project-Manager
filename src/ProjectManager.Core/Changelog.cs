    /// <summary>Commits in <c>start..HEAD</c> (all commits for no start), newest first.</summary>
    public static List<Commit> Commits(Git git, string repo, string? start) =>
        Core.Commits.Log(git, repo, start is null ? "HEAD" : $"{start}..HEAD");

    /// <summary>
    /// Candidates for the start of the range, the preferred one first: the last change of CHANGELOG.md if it holds
    /// another version (= release of the previous version), then the commit that set <c>mod_version</c> to the current
    /// value – or, if nothing was committed after that bump, the commit that set the previous value.
    /// <paramref name="modVersion"/> is the raw value from gradle.properties (<c>1.21.1-2.1.6</c>),
    /// <paramref name="displayVersion"/> the version as written in the changelog (see <see cref="DisplayVersion"/>).
    /// </summary>
    public static List<ChangelogStart> Starts(Git git, string repo, string modVersion, string displayVersion)
    {
        var starts = new List<ChangelogStart>();
        if (git.Value(repo, "log", "-1", "--format=%H", "--", File) is { } c &&
            Show(git, repo, c, File) is { } shown && DetectVersion(shown) is { } version && !SameVersion(version, displayVersion))
            starts.Add(new ChangelogStart(c, $"CHANGELOG.md for {version} ({Abbrev(c)})"));

        // Commits that set a new value of the version property, newest first. "-G version" also finds changes of other
        // lines (minecraft_version, …); of several commits with the same value the oldest one set it.
        var bumps = new List<(string Sha, string Value)>();
        if (git.Value(repo, "log", "--format=%H", "-G", "version", "--", "gradle.properties") is { } log)
        {
            foreach (var sha in Util.Lines(log).Select(l => l.Trim()))
            {
                if (Show(git, repo, sha, "gradle.properties") is not { } props || VersionPropertyOf(props) is not { } value) continue;
                if (bumps.Count > 0 && bumps[^1].Value == value) bumps[^1] = (sha, value);
                else bumps.Add((sha, value));
            }
        }
        var i = bumps.FindIndex(b => b.Value == modVersion);
        if (i >= 0)
        {
            var (sha, value) = bumps[i];
            // The bump commit itself belongs to the release: it often carries the first change of the new version.
            // Its parent is the start; for the root commit the whole history.
            var parent = git.Value(repo, "rev-parse", "--verify", "--quiet", $"{sha}^");
            var withBump = new ChangelogStart(parent, $"mod_version set to {value} ({Abbrev(sha)}, included)");
            var previous = i + 1 < bumps.Count
                ? new ChangelogStart(bumps[i + 1].Sha, $"mod_version set to {bumps[i + 1].Value} ({Abbrev(bumps[i + 1].Sha)})")
                : null;
            var count = git.Value(repo, "rev-list", "--count", $"{sha}..HEAD");
            var nothingAfter = count is null || count == "0";
            // bump as the very last commit = bumped at release time: then the previous bump starts the range
            if (previous is not null && nothingAfter) starts.AddRange([previous, withBump]);
            else if (previous is not null) starts.AddRange([withBump, previous]);
            else starts.Add(withBump);
        }
        starts.Add(new ChangelogStart(null, "Whole history"));
        var seen = new HashSet<string?>();
        return starts.Where(s => seen.Add(s.Sha)).ToList();
    }

    public static string? VersionPropertyOf(string gradleProperties)
    {
        var found = VersionProperty().Matches(gradleProperties).Select(m => (Key: m.Groups[1].Value, Value: m.Groups[2].Value)).ToList();
        return new[] { "mod_version", "modVersion", "version" }
            .Select(k => found.FirstOrDefault(f => f.Key == k).Value)
            .FirstOrDefault(v => v is not null);
    }

    /// <summary>
    /// The mod version as written in the changelog: without a Minecraft prefix or suffix (<c>1.21.1-2.1.6</c> →
    /// <c>2.1.6</c>, <c>2.1.6+1.21.1</c> → <c>2.1.6</c>).
    /// </summary>
    public static string DisplayVersion(string modVersion, string mcVersion)
    {
        var v = modVersion.Trim();
        var mc = mcVersion.Trim();
        if (mc.Length > 0)
        {
            foreach (var prefix in new[] { $"{mc}-", $"{mc}+", $"mc{mc}-" })
                if (v.StartsWith(prefix) && v.Length > prefix.Length) return v[prefix.Length..];
            foreach (var suffix in new[] { $"-{mc}", $"+{mc}", $"+mc{mc}", $"-mc{mc}" })
                if (v.EndsWith(suffix) && v.Length > suffix.Length) return v[..^suffix.Length];
        }
        return v;
    }

    /// <summary>Versions are equal ignoring a leading "v" (<c>v2.1.6</c> = <c>2.1.6</c>).</summary>
    public static bool SameVersion(string a, string b) => StripV(a).Equals(StripV(b), StringComparison.OrdinalIgnoreCase);

    private static string StripV(string v) => v.StartsWith('v') || v.StartsWith('V') ? v[1..] : v;

