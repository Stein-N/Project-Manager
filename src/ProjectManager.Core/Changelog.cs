    private const string EmptyTree = "4b825dc642cb6eb9a060e54bf8d69288fbee4904";

    /// <summary>
    /// Net code changes from <paramref name="start"/> (null = whole history) to HEAD: file statistics and the patch,
    /// limited to about <paramref name="maxChars"/>. Files that do not fit any more are only listed.
    /// </summary>
    public static string Diff(Git git, string repo, string? start, int maxChars)
    {
        var from = start ?? EmptyTree;
        string[] stat = ["diff", "--stat=160", "--no-color", from, "HEAD", "--", ".", .. DiffExcludes];
        string[] patch = ["diff", "--no-color", "--unified=3", from, "HEAD", "--", ".", .. DiffExcludes];
        return LimitDiff(git.Output(repo, stat), git.Output(repo, patch), maxChars);
    }

    public static string LimitDiff(string summary, string patch, int maxChars)
    {
        var sb = new StringBuilder($"{summary.Trim()}\n\n");
        var omitted = new List<string>();
        foreach (var file in SplitKeep(patch, "diff --git "))
        {
            if (file.Trim().Length == 0) continue;
            if (sb.Length + file.Length <= maxChars)
            {
                sb.Append(file);
                if (!file.EndsWith('\n')) sb.Append('\n');
            }
            else
            {
                var first = file.Split('\n')[0];
                var name = first.StartsWith("diff --git a/") ? first["diff --git a/".Length..].Split(" b/")[0] : first;
                omitted.Add(name);
            }
        }
        if (omitted.Count > 0)
            sb.Append($"\n(diff of {omitted.Count} more file(s) left out because of its size: {string.Join(", ", omitted)})\n");
        return sb.ToString();
    }

    /// <summary>Splits <paramref name="text"/> before every line that starts with <paramref name="marker"/>.</summary>
    private static List<string> SplitKeep(string text, string marker)
    {
        var starts = new List<int>();
        for (var i = text.IndexOf(marker, StringComparison.Ordinal); i >= 0; i = text.IndexOf(marker, i + 1, StringComparison.Ordinal))
            if (i == 0 || text[i - 1] == '\n') starts.Add(i);
        if (starts.Count == 0 || starts[0] != 0) starts.Insert(0, 0);
        return starts.Select((s, n) => text[s..(n + 1 < starts.Count ? starts[n + 1] : text.Length)]).ToList();
    }

    /// <summary>Cleans Claude's answer; null if it does not start with a heading for <paramref name="version"/>.</summary>
    public static string? CleanAnswer(string answer, string version)
    {
        var text = answer.Replace("\r\n", "\n").Trim();
        foreach (var fence in new[] { "```markdown\n", "```md\n", "```\n" })
        {
            if (!text.StartsWith(fence)) continue;
            text = text[fence.Length..];
            break;
        }
        if (text.EndsWith("\n```")) text = text[..^4];
        text = text.Trim();
        if (FirstVersionHeading(text) is not { } start) return null;
        text = text[start..];
        return DetectVersion(text) is { } v && SameVersion(v, version) ? $"{text}\n" : null;
    }

    /// <summary>The section about changelogs from a CLAUDE.md (a heading containing "changelog").</summary>
    public static string? RulesFromClaudeMd(string claudeMd)
    {
        StringBuilder? sb = null;
        var level = 0;
        foreach (var line in claudeMd.Replace("\r\n", "\n").Split('\n'))
        {
            var h = AnyHeading().Match(line);
            if (h.Success)
            {
                var l = h.Groups[1].Length;
                if (sb is not null && l <= level) break;
                if (sb is null && h.Groups[2].Value.ToLowerInvariant().Contains("changelog"))
                {
                    sb = new StringBuilder();
                    level = l;
                    continue;
                }
            }
            sb?.Append(line).Append('\n');
        }
        return sb?.ToString().Trim() is { Length: > 0 } s ? s : null;
    }

