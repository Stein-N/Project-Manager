package net.morthen.core;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.atomic.AtomicLong;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Finds Gradle cache data (Gradle user home and project build output) and marks what no project uses.
 */
public final class GradleCache {
    public enum Status {
        /** Used by at least one project in the master folder. */
        USED,
        /** Not used by any project in the master folder. */
        UNUSED,
        /** Shared cache that cannot be attributed to projects – deleting causes a re-download. */
        SHARED,
        /** Build output inside a project – regenerated by the next build. */
        BUILD_OUTPUT
    }

    public record Item(String category, Path path, String name, Status status, String usedBy) {
    }

    private static final Pattern GRADLE_VERSION = Pattern.compile("\\d+(\\.\\d+)+(-rc-\\d+|-milestone-\\d+)?");
    private static final Pattern WRAPPER_DIST = Pattern.compile("gradle-(.+)-(bin|all)");
    private static final Pattern MC_VERSION = Pattern.compile("\\d+\\.\\d+(\\.\\d+)?(-(pre|rc)\\d+)?|\\d{2}w\\d{2}[a-z]");
    private static final List<String> SUBPROJECTS = List.of("", "fabric", "neoforge", "forge", "quilt", "common");

    private GradleCache() {
    }

    public static Path gradleHome() {
        String env = System.getenv("GRADLE_USER_HOME");
        return env != null && !env.isBlank() ? Path.of(env) : Path.of(System.getProperty("user.home"), ".gradle");
    }

    public static List<Item> scan(Path gradleHome, List<ModProject> projects) throws IOException {
        Map<String, Set<String>> gradleUsers = new LinkedHashMap<>();
        Map<String, Set<String>> mcUsers = new LinkedHashMap<>();
        for (ModProject p : projects) {
            String label = p.mcVersion() + "/" + p.name();
            Dependencies.wrapperVersion(p.path()).ifPresent(v -> gradleUsers.computeIfAbsent(v, k -> new LinkedHashSet<>()).add(label));
            mcUsers.computeIfAbsent(p.mcVersion(), k -> new LinkedHashSet<>()).add(label);
            if (p.gradleMcVersion() != null) mcUsers.computeIfAbsent(p.gradleMcVersion(), k -> new LinkedHashSet<>()).add(label);
        }

        List<Item> items = new ArrayList<>();

        // --- Gradle distributions downloaded by the wrapper
        for (Path dist : children(gradleHome.resolve("wrapper/dists"))) {
            var m = WRAPPER_DIST.matcher(dist.getFileName().toString());
            String version = m.matches() ? m.group(1) : null;
            items.add(attributed("Gradle distribution", dist, version, gradleUsers));
        }

        // --- version specific caches and daemon data
        Path caches = gradleHome.resolve("caches");
        for (Path dir : children(caches)) {
            String name = dir.getFileName().toString();
            if (GRADLE_VERSION.matcher(name).matches()) {
                items.add(attributed("Gradle " + name + " cache", dir, name, gradleUsers));
            } else if (name.equals("fabric-loom")) {
                for (Path loom : children(dir)) {
                    String loomName = loom.getFileName().toString();
                    items.add(MC_VERSION.matcher(loomName).matches()
                            ? attributed("Loom (Minecraft " + loomName + ")", loom, loomName, mcUsers)
                            : new Item("Loom shared", loom, "fabric-loom/" + loomName, Status.SHARED, null));
                }
            } else {
                items.add(new Item(sharedCategory(name), dir, "caches/" + name, Status.SHARED, null));
            }
        }
        for (Path dir : children(gradleHome.resolve("daemon"))) {
            String name = dir.getFileName().toString();
            if (GRADLE_VERSION.matcher(name).matches()) {
                items.add(attributed("Gradle " + name + " daemon logs", dir, name, gradleUsers));
            }
        }
        for (Path jdk : children(gradleHome.resolve("jdks"))) {
            items.add(new Item("Toolchain JDK", jdk, "jdks/" + jdk.getFileName(), Status.SHARED, null));
        }

        // --- build output inside the projects
        for (ModProject p : projects) {
            String label = p.mcVersion() + "/" + p.name();
            for (String sub : SUBPROJECTS) {
                Path base = sub.isEmpty() ? p.path() : p.path().resolve(sub);
                for (String out : List.of("build", ".gradle")) {
                    Path dir = base.resolve(out);
                    if (Files.isDirectory(dir)) {
                        String rel = (sub.isEmpty() ? "" : sub + "/") + out;
                        items.add(new Item("Project build output", dir, label + "/" + rel, Status.BUILD_OUTPUT, label));
                    }
                }
            }
        }

        items.sort(Comparator.comparing(Item::status).thenComparing(Item::category).thenComparing(Item::name));
        // UNUSED first – it is what the user is looking for
        items.sort(Comparator.comparing((Item i) -> i.status() != Status.UNUSED));
        return items;
    }

    private static Item attributed(String category, Path dir, String key, Map<String, Set<String>> users) {
        Set<String> by = key == null ? null : users.get(key);
        String name = dir.getFileName().toString();
        if (by == null || by.isEmpty()) return new Item(category, dir, name, Status.UNUSED, null);
        return new Item(category, dir, name, Status.USED, String.join(", ", by));
    }

    private static String sharedCategory(String name) {
        if (name.equals("modules-2")) return "Dependency cache";
        if (name.startsWith("transforms") || name.startsWith("jars")) return "Gradle transforms";
        if (name.startsWith("build-cache")) return "Build cache";
        if (Set.of("neoformruntime", "minecraft", "forge_gradle", "minecraftforge").contains(name)) return "(Neo)Forge cache";
        return "Shared cache";
    }

    private static List<Path> children(Path dir) throws IOException {
        if (!Files.isDirectory(dir)) return List.of();
        try (Stream<Path> stream = Files.list(dir)) {
            return stream.filter(Files::isDirectory).sorted().toList();
        }
    }

    /** Total size in bytes; unreadable files are skipped. */
    public static long size(Path path) {
        AtomicLong total = new AtomicLong();
        try {
            Files.walkFileTree(path, new SimpleFileVisitor<>() {
                @Override
                public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) {
                    total.addAndGet(attrs.size());
                    return FileVisitResult.CONTINUE;
                }

                @Override
                public FileVisitResult visitFileFailed(Path file, IOException exc) {
                    return FileVisitResult.CONTINUE;
                }
            });
        } catch (IOException ignored) {
            // partial size is fine
        }
        return total.get();
    }

    public static String formatSize(long bytes) {
        if (bytes < 1024) return bytes + " B";
        String[] units = {"KB", "MB", "GB", "TB"};
        double value = bytes;
        int unit = -1;
        while (value >= 1024 && unit < units.length - 1) {
            value /= 1024;
            unit++;
        }
        return String.format(java.util.Locale.ROOT, value >= 100 ? "%.0f %s" : "%.1f %s", value, units[unit]);
    }
}
